/**
 * Контракт справочника продуктов (SKU).
 *
 * Продукт — общая единица между ТТК и складом: у него есть только имя и единица
 * закупки. Цены в нём НЕ хранятся — они берутся из приходных склада (последняя
 * цена по продукту). КБЖУ и категории убраны как невостребованные.
 *
 * Создаётся продукт inline в момент использования: в ТТК (состав рецепта) или
 * в приходной склада, когда нужного товара ещё нет в справочнике.
 *
 * Бэкенд — ProductsService в onemore-admin (/v1/products). Справочник
 * отдаётся целиком, поиск по нему делает фронтенд.
 */

/** Продукт (SKU). Единица — закупочная (кг, л, шт и т.п.). */
export interface Product {
  id: string;
  name: string;
  /** Единица закупки: кг, л, шт и т.п. */
  unit: string;
  /**
   * Вода — общий для всех организаций продукт, только для состава ТТК:
   * бесплатная, на склад не приходуется, изменить и удалить её нельзя.
   */
  water?: boolean;
}

/** Тело создания продукта — те же поля, что и в Product. */
export interface CreateProductRequest {
  name: string;
  unit: string;
}

/** Тело обновления продукта — те же поля, что и при создании. */
export type UpdateProductRequest = CreateProductRequest;

/**
 * Режим удаления продукта: immediate — убрать из справочника сразу,
 * soft — после конца периода (пока он ещё нужен ТТК и закупкам).
 *
 * Бэкенд принимает режим, но пока не различает: периодов нет, и оба режима
 * убирают продукт из справочника сразу.
 */
export type ProductDeleteMode = 'immediate' | 'soft';

export interface ListProductsResponse {
  products: Product[];
  total: number;
}
